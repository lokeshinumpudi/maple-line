// Regenerates docs/drama/THE-1742.md from the episode data the game plays.
import { writeFileSync } from 'node:fs';
import { normalizeEpisode } from '../src/drama/episode-schema.js';
import { seriesScreenplay } from '../src/drama/screenplay.js';
import { THE_1742 } from '../src/drama/series/the-1742.js';
import { additionalStops } from '../src/world/extended-route.js';
import { LEVEL_CROSSINGS } from '../src/world/level-crossings.js';

const context = {
  stops: ['momiji', ...additionalStops.map((stop) => stop.id)],
  crossings: LEVEL_CROSSINGS.map((site) => site.id),
};
const intro = `<!-- Generated by apps/game/scripts/write-drama-script.mjs from apps/game/src/drama/series/the-1742.js. Edit the episode data, then run: pnpm --filter @maple-line/game drama:script -->

`;
const target = new URL('../../../docs/drama/THE-1742.md', import.meta.url);
writeFileSync(
  target,
  intro + seriesScreenplay(THE_1742, (episode) => normalizeEpisode(episode, context)) + '\n',
);
console.log(`Wrote ${target.pathname}`);
